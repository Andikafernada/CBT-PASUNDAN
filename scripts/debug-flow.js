const http = require("http");

const BASE_URL = "http://172.16.0.210";

function login(username, password) {
  return new Promise((resolve, reject) => {
    const postData = JSON.stringify({ username, password, deviceFingerprint: `DEV_${username}_E2E` });
    const req = http.request(
      new URL("/api/auth/login", BASE_URL),
      {
        method: "POST",
        headers: { "Content-Type": "application/json", "Content-Length": Buffer.byteLength(postData) },
      },
      (res) => {
        let data = "";
        res.on("data", (c) => (data += c));
        res.on("end", () => {
          const rawCookies = res.headers["set-cookie"] || [];
          let tokenCookie = "";
          for (const c of rawCookies) {
            if (c.startsWith("cbt_token=")) {
              tokenCookie = c.split(";")[0];
              break;
            }
          }
          resolve({ status: res.statusCode, cookie: tokenCookie, body: JSON.parse(data || "{}") });
        });
      }
    );
    req.on("error", reject);
    req.write(postData);
    req.end();
  });
}

function reqApi(path, method = "GET", cookie = "", body = null) {
  return new Promise((resolve, reject) => {
    const postData = body ? JSON.stringify(body) : "";
    const req = http.request(
      new URL(path, BASE_URL),
      {
        method,
        headers: {
          ...(cookie ? { Cookie: cookie } : {}),
          ...(body ? { "Content-Type": "application/json", "Content-Length": Buffer.byteLength(postData) } : {}),
        },
      },
      (res) => {
        let data = "";
        res.on("data", (c) => (data += c));
        res.on("end", () => {
          try {
            resolve({ status: res.statusCode, body: JSON.parse(data || "{}") });
          } catch {
            resolve({ status: res.statusCode, raw: data });
          }
        });
      }
    );
    req.on("error", reject);
    if (body) req.write(postData);
    req.end();
  });
}

async function debugFlow() {
  const admin = await login("admin", "admin123");
  console.log("Admin Login:", admin.status, "Cookie length:", admin.cookie.length);

  const grpRes = await reqApi("/api/admin/students", "POST", admin.cookie, {
    action: "CREATE_GROUP",
    code: `TKJ-${Date.now().toString().slice(-4)}`,
    name: "X TKJ Uji Terpadu",
  });
  console.log("Group Create:", grpRes.status, grpRes.body);

  const subRes = await reqApi("/api/admin/subjects", "POST", admin.cookie, {
    code: `ASJ-${Date.now().toString().slice(-4)}`,
    name: "Administrasi Server Jaringan E2E",
  });
  console.log("Subject Create:", subRes.status, subRes.body);
}

debugFlow().catch(console.error);
